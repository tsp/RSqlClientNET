# Run from the package source directory; no SQL Server is required.
source("tools/ensure-deps.R", local = TRUE)
rscn_ensure_dev_deps("document")
if (!requireNamespace("roxygen2", quietly = TRUE)) {
  stop("Install roxygen2 first: install.packages('roxygen2')", call. = FALSE)
}
# Isolate pkgload::load_all() so this script does not register the source tree
# as a pseudo-installed package in the caller's R session.
if (!requireNamespace("callr", quietly = TRUE)) {
  stop("Install callr first: install.packages('callr')", call. = FALSE)
}
callr::r(
  function(path) {
    roxygen2::roxygenise(path)
    invisible(TRUE)
  },
  args = list(normalizePath(".", mustWork = TRUE)),
  show = TRUE
)

# Confirm the DBI S4 exports and the primary help topics survived regeneration.
ns <- paste(readLines("NAMESPACE", warn = FALSE), collapse = "\n")
expected_ns <- c(
  "useDynLib(RSqlClientNET", "import(DBI)", "importFrom(bit64,as.integer64)",
  "export(SqlClientNET)", "exportClasses(SqlClientNETDriver,SqlClientNETConnection,SqlClientNETResult)",
  "exportMethods(dbWriteTable,dbAppendTable,dbCreateTable,dbRemoveTable)"
)
for (pattern in expected_ns) {
  if (!grepl(pattern, ns, fixed = TRUE)) stop("Missing NAMESPACE directive: ", pattern)
}
required <- c(
  "SqlClientNET", "sql_cancel", "sql_pipe_stats", "sql_process_memory",
  "sql_query_stream", "RSqlClientNET-db-write", "RSqlClientNET-dbplyr",
  "RSqlClientNET-internal-tests", "RSqlClientNET-types", "RSqlClientNET-validation",
  "RSqlClientNET", "RSqlClientNET-package",
  "RSqlClientNET-db-connect", "RSqlClientNET-db-query", "RSqlClientNET-db-result",
  "RSqlClientNET-db-read", "RSqlClientNET-db-transaction"
)
for (nm in required) {
  path <- file.path("man", paste0(nm, ".Rd"))
  if (!file.exists(path)) stop("Missing help topic: ", path)
  tools::parse_Rd(path) # Validates Rd syntax.
  lines <- readLines(path, warn = FALSE)
  expected_name <- paste0("\\name{", nm, "}")
  if (!any(lines == expected_name)) {
    stop("Wrong Rd \\name in ", path, "; expected ", expected_name,
         call. = FALSE)
  }
}

# These topic filenames once differed from their @name tags, causing
# roxygen2 to remove the previous .Rd files and generate others.
# Test both the filenames and the aliases used in ?sql_connect etc.
required_aliases <- list(
  "RSqlClientNET.Rd" = c("sql_connect", "sqlclient_build", "sql_query"),
  "RSqlClientNET-types.Rd" = c("sql_schema", "sql_param"),
  "RSqlClientNET-validation.Rd" = c("sql_connection_status", "sql_reconnect"),
  "SqlClientNET.Rd" = c("SqlClientNET"),
  "RSqlClientNET-db-connect.Rd" = c("dbConnect", "dbDisconnect"),
  "RSqlClientNET-db-query.Rd" = c("dbGetQuery", "dbExecute", "dbSendQuery", "dbSendStatement"),
  "RSqlClientNET-db-result.Rd" = c("dbFetch", "dbBind", "dbClearResult"),
  "RSqlClientNET-db-write.Rd" = c("dbWriteTable", "dbAppendTable", "dbCreateTable", "dbRemoveTable"),
  "RSqlClientNET-db-read.Rd" = c("dbReadTable", "dbListTables", "dbListFields", "dbExistsTable"),
  "RSqlClientNET-db-transaction.Rd" = c("dbBegin", "dbCommit", "dbRollback")
)
for (file in names(required_aliases)) {
  path <- file.path("man", file)
  if (!file.exists(path)) stop("Missing help topic: ", path)
  rd <- paste(readLines(path, warn = FALSE), collapse = "\n")
  for (alias in required_aliases[[file]]) {
    token <- paste0("\\alias{", alias, "}")
    if (!grepl(token, rd, fixed = TRUE)) {
      stop("Missing help alias ", alias, " in ", path, call. = FALSE)
    }
  }
}

cat("roxygen2 documentation regenerated; core namespace and Rd files found.\n")

# DBItest checks full reexports only in an installed package under R CMD check.
arrow_generics <- c("dbAppendTableArrow", "dbBindArrow", "dbCreateTableArrow",
                    "dbFetchArrow", "dbFetchArrowChunk", "dbGetQueryArrow",
                    "dbReadTableArrow", "dbSendQueryArrow", "dbWriteTableArrow")
for (nm in arrow_generics) {
  if (!grepl(paste0("export(", nm), ns, fixed = TRUE)) {
    # The generics are exported in a grouped export(...) directive.
    if (!grepl(nm, ns, fixed = TRUE)) stop("Arrow reexport absent: ", nm)
  }
}
for (topic in names(required_aliases)) {
  # Method aliases are generated by roxygen from @aliases in R/zzz-documentation.R.
  # Check at least one particularly important dispatch alias.
  if (topic == "RSqlClientNET-db-query.Rd") {
    rd <- paste(readLines(file.path("man",topic), warn = FALSE), collapse = "\n")
    stopifnot(grepl("\\alias{dbQuoteLiteral,SqlClientNETConnection,ANY-method}", rd, fixed=TRUE))
  }
}
