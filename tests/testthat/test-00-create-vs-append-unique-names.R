testthat::test_that("benchmark table identifiers stay unique after reseeding", {
  src <- file.path("tools", "benchmarks", "benchmark-create-vs-append.R")
  if (!file.exists(src)) src <- file.path("..", "..", src)
  if (!file.exists(src)) testthat::skip("Benchmark script is not available")
  env <- new.env(parent = globalenv())
  sys.source(src, envir = env)
  set.seed(20261029L)
  one <- env$.create_append_run_id()
  set.seed(20261029L)
  two <- env$.create_append_run_id()
  testthat::expect_false(identical(one, two))
  testthat::expect_match(one, "^[A-Za-z0-9_]+$")
  testthat::expect_match(two, "^[A-Za-z0-9_]+$")
  testthat::expect_lt(nchar(paste0("rscn_ca35_", one, "_log_6")), 128L)
})
