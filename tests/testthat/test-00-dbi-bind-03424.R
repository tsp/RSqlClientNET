testthat::test_that("nested DBI blob wrappers normalize to raw or NULL", {
  unwrap <- getFromNamespace(".sql_unwrap_binary_param", "RSqlClientNET")
  encode <- getFromNamespace(".sql_encode_params", "RSqlClientNET")
  expect_identical(unwrap(list(list(as.raw(1:10)))), as.raw(1:10))
  expect_identical(unwrap(list(list(raw(0)))), raw(0))
  expect_null(unwrap(list(list(NULL))))
  expect_identical(unwrap(list(123L)), list(123L))
  expect_identical(unwrap(list(list("text"))), list(list("text")))
  expect_identical(encode(list(a=list(list(as.raw(1:10)))))$a$`$sqlclient_type`, "varbinary")
  expect_identical(encode(list(a=list(list(raw(0)))))$a$value, "")
  expect_null(encode(list(a=list(list(NULL))))$a)
  expect_error(encode(list(a=list(1L, 2L))), "scalar")
})

testthat::test_that("DBItest raw/blob shapes remain binary scalar parameters", {
  split <- getFromNamespace(".dbi_param_sets", "RSqlClientNET")
  encode <- getFromNamespace(".sql_encode_params", "RSqlClientNET")
  values <- list(a=list(as.raw(1:10)),b=list(raw(3)),c=list(NULL))
  rows <- split(values)
  expect_length(rows, 1L)
  p <- encode(rows[[1L]])
  expect_identical(p$a$`$sqlclient_type`, "varbinary")
  expect_identical(p$b$`$sqlclient_type`, "varbinary")
  expect_null(p$c)
  expect_identical(jsonlite::base64_dec(p$a$value), as.raw(1:10))
  expect_identical(jsonlite::base64_dec(p$b$value), raw(3))
  testthat::skip_if_not_installed("blob")
  b <- list(a=blob::blob(as.raw(1:10)),
            b=blob::blob(raw(3)), c=blob::blob(NULL))
  result <- encode(split(b)[[1L]])
  expect_identical(result$a$`$sqlclient_type`, "varbinary")
  expect_identical(result$b$`$sqlclient_type`, "varbinary")
  expect_null(result$c)
})


testthat::test_that("SQL Server timestamp SQL literals have no timezone suffix", {
  quote <- getFromNamespace(".dbi_quote_timestamp", "RSqlClientNET")
  x <- as.POSIXct(c("2023-12-17 02:40:22","2023-12-17 02:40:23",NA), tz="UTC")
  output <- as.character(quote(x))
  expect_identical(output[[1L]], "CAST('2023-12-17T02:40:22.000000' AS datetime2(7))")
  expect_identical(output[[2L]], "CAST('2023-12-17T02:40:23.000000' AS datetime2(7))")
  expect_identical(output[[3L]], "NULL")
  expect_identical(as.character(quote(as.POSIXlt(x)))[[1L]], output[[1L]])
})
