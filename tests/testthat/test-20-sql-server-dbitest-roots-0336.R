testthat::test_that("SQL Server: bracket identifier unquote and quoted bulk column", {
  cs <- Sys.getenv("RSQLCLIENTNET_TEST_CONNECTION_STRING", "")
  testthat::skip_if(!nzchar(cs), "RSQLCLIENTNET_TEST_CONNECTION_STRING not set")
  con <- DBI::dbConnect(RSqlClientNET::SqlClientNET(),connection_string=cs)
  on.exit(if (DBI::dbIsValid(con)) DBI::dbDisconnect(con),add=TRUE)
  for (nm in c("a.b", "with space", "a]b", "[]", "", "a'b")) {
    q <- DBI::dbQuoteIdentifier(con,nm)
    unq <- DBI::dbUnquoteIdentifier(con,q)
    testthat::expect_identical(DBI::dbQuoteIdentifier(con,unq[[1L]]),q)
  }
  testthat::expect_identical(as.character(DBI::dbQuoteLiteral(con,as.raw(1))),"0x01")
  x <- data.frame(a=1:2,b=c("first","second"),check.names=FALSE)
  names(x) <- c("a]b", "with space")
  DBI::dbWriteTable(con,"#quote0336",x)
  y <- DBI::dbReadTable(con,"#quote0336")
  testthat::expect_identical(names(y),names(x))
  testthat::expect_identical(y[[1]],x[[1]])
  DBI::dbRemoveTable(con,"#quote0336")
  z <- data.frame(a=1:3,row.names=c("one","two","three"))
  DBI::dbWriteTable(con,"#rownames0336",z,row.names=TRUE)
  testthat::expect_identical(rownames(DBI::dbReadTable(con,"#rownames0336",row.names=TRUE)),rownames(z))
  testthat::expect_true("row_names" %in% names(DBI::dbReadTable(con,"#rownames0336")))
  DBI::dbRemoveTable(con,"#rownames0336")
})
