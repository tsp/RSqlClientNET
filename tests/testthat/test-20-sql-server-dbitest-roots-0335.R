testthat::test_that("SQL Server: DBI data.frame default, opt-in data.table and one-column bulk", {
  cs <- Sys.getenv("RSQLCLIENTNET_TEST_CONNECTION_STRING", "")
  testthat::skip_if(!nzchar(cs), "RSQLCLIENTNET_TEST_CONNECTION_STRING not set")
  con <- DBI::dbConnect(RSqlClientNET::SqlClientNET(), connection_string=cs)
  on.exit(if (DBI::dbIsValid(con)) DBI::dbDisconnect(con), add=TRUE)
  result <- DBI::dbGetQuery(con, "SELECT CAST(1 AS INT) AS a")
  testthat::expect_identical(class(result), "data.frame")
  testthat::expect_identical(result$a, 1L)
  testthat::expect_identical(length(DBI::dbQuoteIdentifier(con, character())), 0L)
  testthat::expect_identical(as.character(DBI::dbQuoteIdentifier(con, "")), "[]")
  testthat::expect_error(DBI::dbQuoteString(con, 1:3))
  testthat::expect_identical(as.character(DBI::dbQuoteString(con, "O'Brien")), "N'O''Brien'")
  testthat::expect_identical(as.character(DBI::dbQuoteString(con, NA_character_)), "NULL")
  testthat::expect_false(DBI::dbExistsTable(con, "#single0335"))
  DBI::dbWriteTable(con,"#single0335",data.frame(v=c(1L,2L,3L)),temporary=FALSE)
  testthat::expect_identical(DBI::dbReadTable(con,"#single0335")$v,1:3)
  DBI::dbRemoveTable(con,"#single0335")
  fast <- DBI::dbConnect(RSqlClientNET::SqlClientNET(), connection_string=cs, data_table=TRUE)
  on.exit(if (DBI::dbIsValid(fast)) DBI::dbDisconnect(fast), add=TRUE)
  testthat::expect_s3_class(DBI::dbGetQuery(fast,"SELECT CAST(2 AS INT) AS a"),"data.table")
})

testthat::test_that("SQL Server: active result warning on disconnect", {
  cs <- Sys.getenv("RSQLCLIENTNET_TEST_CONNECTION_STRING", "")
  testthat::skip_if(!nzchar(cs), "RSQLCLIENTNET_TEST_CONNECTION_STRING not set")
  con <- DBI::dbConnect(RSqlClientNET::SqlClientNET(),connection_string=cs)
  res <- DBI::dbSendQuery(con,"SELECT CAST(1 AS INT) AS a")
  testthat::expect_warning(DBI::dbDisconnect(con),"active result")
  testthat::expect_false(DBI::dbIsValid(res))
})
