testthat::test_that("DBI binary literals, scalar/list encodings and invalid options", {
  cs <- Sys.getenv("RSQLCLIENTNET_TEST_CONNECTION_STRING", "")
  testthat::skip_if(!nzchar(cs), "RSQLCLIENTNET_TEST_CONNECTION_STRING not set")
  con <- DBI::dbConnect(RSqlClientNET::SqlClientNET(),connection_string=cs)
  on.exit(if (DBI::dbIsValid(con)) DBI::dbDisconnect(con),add=TRUE)
  testthat::expect_identical(as.character(DBI::dbQuoteLiteral(con,list(as.raw(0),NULL))),
                             c("0x00","NULL"))
  testthat::expect_identical(as.character(DBI::dbQuoteLiteral(con,list())),character())
  testthat::expect_identical(as.character(DBI::dbQuoteLiteral(con,as.raw(255))),"0xFF")
  testthat::expect_equal(DBI::dbGetQuery(con,"SELECT CAST(0x00 AS VARBINARY(MAX)) AS x")$x[[1]],as.raw(0))
  testthat::expect_error(DBI::dbCommit(con),"no active")
  testthat::expect_true(DBI::dbIsValid(con))
  testthat::expect_error(DBI::dbRollback(con),"no active")
  testthat::expect_true(DBI::dbIsValid(con))
  DBI::dbBegin(con)
  testthat::expect_error(DBI::dbBegin(con),"already active")
  DBI::dbRollback(con)
  testthat::expect_true(DBI::dbIsValid(con))
  testthat::expect_equal(DBI::dbGetQuery(con,"SELECT 1 AS a")$a,1L)
  r <- DBI::dbSendQuery(con,"SELECT 1 AS a")
  testthat::expect_identical(DBI::dbGetRowsAffected(r),0L)
  testthat::expect_true("has.completed" %in% names(DBI::dbGetInfo(r)))
  DBI::dbClearResult(r)
  testthat::expect_error(DBI::dbWriteTable(con,"_invalid_append",data.frame(a=1L),append=TRUE,field.types=c(a="INTEGER")))
  testthat::expect_false(DBI::dbExistsTable(con,"_invalid_append"))
})
